def _normal_url(adres: str) -> str:
    link = adres.strip()
    if not re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*://", link):
        link = "https://" + link.lstrip("/")
    try:
        parcalar = urlsplit(link)
        port = parcalar.port
    except ValueError:
        return link.lower()
    alan_adi = (parcalar.hostname or "").lower().removeprefix("www.")
    if port in (80, 443):
        port = None
    sorgu = urlencode(
        sorted(
            (ad, deger)
            for ad, deger in parse_qsl(parcalar.query, keep_blank_values=True)
            if not ad.lower().startswith("utm_") and ad.lower() not in _IZLEME
        )
    )
    yol = parcalar.path.rstrip("/")
    return f"https://{alan_adi}{f':{port}' if port else ''}{yol}{f'?{sorgu}' if sorgu else ''}"


